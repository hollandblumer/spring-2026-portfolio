create table if not exists public.goal_tracker_family_notes (
  id uuid primary key default gen_random_uuid(),
  author_user_id uuid not null references auth.users(id) on delete cascade,
  author_profile text not null check (author_profile in ('mom', 'dad')),
  category text not null check (category in ('Career', 'Health', 'Household chores')),
  note_kind text not null check (note_kind in ('Note', 'Compliment')),
  message text not null check (char_length(message) between 1 and 1000),
  note_date date not null default current_date,
  created_at timestamptz not null default now()
);

alter table public.goal_tracker_family_notes
