create table if not exists public.goal_tracker_data (
  user_id uuid primary key references auth.users(id) on delete cascade,
  profile_id text check (profile_id in ('me', 'mom', 'dad')),
  tracker_state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.goal_tracker_data
add column if not exists profile_id text check (profile_id in ('me', 'mom', 'dad'));

update public.goal_tracker_data as tracker
set profile_id = case users.email
  when 'hollandblumer6@icloud.com' then 'me'
  when 'goal-tracker-mom@hollandblumer.com' then 'mom'
  when 'goal-tracker-dad@hollandblumer.com' then 'dad'
end
from auth.users as users
where tracker.user_id = users.id
  and tracker.profile_id is null;

alter table public.goal_tracker_data enable row level security;

drop policy if exists "Users can read their tracker" on public.goal_tracker_data;
create policy "Users can read their tracker"
on public.goal_tracker_data for select
using (
  auth.uid() = user_id
  or (
    profile_id = 'me'
    and (auth.jwt() ->> 'email') in (
      'goal-tracker-mom@hollandblumer.com',
      'goal-tracker-dad@hollandblumer.com'
    )
  )
);

drop policy if exists "Users can create their tracker" on public.goal_tracker_data;
create policy "Users can create their tracker"
on public.goal_tracker_data for insert
with check (
  auth.uid() = user_id
  and profile_id = case (auth.jwt() ->> 'email')
    when 'hollandblumer6@icloud.com' then 'me'
    when 'goal-tracker-mom@hollandblumer.com' then 'mom'
    when 'goal-tracker-dad@hollandblumer.com' then 'dad'
  end
);

drop policy if exists "Users can update their tracker" on public.goal_tracker_data;
create policy "Users can update their tracker"
on public.goal_tracker_data for update
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
  and profile_id = case (auth.jwt() ->> 'email')
    when 'hollandblumer6@icloud.com' then 'me'
    when 'goal-tracker-mom@hollandblumer.com' then 'mom'
    when 'goal-tracker-dad@hollandblumer.com' then 'dad'
  end
);

create index if not exists goal_tracker_data_profile_idx
on public.goal_tracker_data (profile_id);

