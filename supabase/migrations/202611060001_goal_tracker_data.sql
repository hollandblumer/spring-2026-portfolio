on public.goal_tracker_family_notes for select
using (
  auth.uid() = author_user_id
  or (auth.jwt() ->> 'email') = 'hollandblumer6@icloud.com'
);

drop policy if exists "Family notes can be removed by their author or Me" on public.goal_tracker_family_notes;
create policy "Family notes can be removed by their author or Me"
on public.goal_tracker_family_notes for delete
using (
  auth.uid() = author_user_id
  or (auth.jwt() ->> 'email') = 'hollandblumer6@icloud.com'
